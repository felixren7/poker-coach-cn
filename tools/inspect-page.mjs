const CDP='http://127.0.0.1:9223';
const pages=await (await fetch(`${CDP}/json/list`)).json();
const page=pages.find(p=>p.type==='page');
const ws=new WebSocket(page.webSocketDebuggerUrl);
await new Promise((r,j)=>{ws.onopen=r;ws.onerror=j});
let id=0;const pend=new Map();
ws.onmessage=e=>{const m=JSON.parse(e.data);if(m.id){const p=pend.get(m.id);if(p){pend.delete(m.id);m.error?p.j(new Error(m.error.message)):p.r(m.result)}}};
const send=(method,params={})=>new Promise((r,j)=>{const i=++id;pend.set(i,{r,j});ws.send(JSON.stringify({id:i,method,params}))});
const evalx=async(expression)=>{const r=await send('Runtime.evaluate',{expression,returnByValue:true,awaitPromise:true});if(r.exceptionDetails)throw new Error(r.exceptionDetails.exception?.description||r.exceptionDetails.text);return r.result?.value};
await send('Page.enable');await send('Runtime.enable');
await send('Page.reload',{ignoreCache:true});await new Promise(r=>setTimeout(r,1400));
await evalx(`location.hash='#/lesson/L1'`);await new Promise(r=>setTimeout(r,1200));
console.log('player count',await evalx(`document.querySelectorAll('.question-player').length`));
console.log('demo section',await evalx(`document.querySelector('.lesson-demo-section')?.innerHTML?.slice(0,1200)||'NONE'`));
console.log('demo buttons',await evalx(`[...document.querySelectorAll('.lesson-demo-section button')].map(b=>({t:(b.innerText||'').trim(),c:b.className})).slice(0,20)`));
console.log('all question titles',await evalx(`[...document.querySelectorAll('.question-title')].map(e=>e.innerText)`));
console.log('demo q count',await evalx(`document.querySelectorAll('.lesson-demo-section .question-player').length`));
console.log('practice q count',await evalx(`document.querySelectorAll('.lesson-practice-section .question-player').length`));
console.log('errors',await evalx(`window.__errs||null`));
ws.close();
